//! 設定の読み書きと検証(spec.md 10章)。
//!
//! - ファイルに書くのはこのモジュールだけ(S-03、S-06)。書き込み先は exe と同じフォルダーの
//!   設定ファイル1つと、保存時の一時ファイルだけ。画面の内容に由来するデータは含めない。
//! - 設定ファイルは信頼しない(S-07)。大きさに上限を設け、型と範囲を検証し、範囲外は既定値に
//!   置き換える。壊れていても起動する。
//!
//! OS に依存しない。Linux 上でも単体テストできる。

#![forbid(unsafe_code)]

/// 設定ファイルの名前。exe と同じフォルダーに置く(S-06)。
pub const FILE_NAME: &str = "monitoaster.json";

/// 設定ファイルの大きさの上限(バイト)。これを超える設定は既定値に落とす(S-07)。
///
/// 読み込みは上限+1バイトで打ち切り、超えたかどうかを見る。サイズを調べてから読む方式にはしない。
pub const MAX_FILE_BYTES: u64 = 64 * 1024;
